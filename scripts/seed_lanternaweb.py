def run() -> None:
    init_db()
    db = SessionLocal()

    token = os.environ.get("LANTERNAWEB_TELEGRAM_TOKEN", "").strip()

    tenant = db.query(Tenant).filter(Tenant.slug == SLUG).first()
    if tenant:
        tenant.name = "Lanternaweb"
        tenant.system_prompt = SYSTEM_PROMPT
        if token:
            tenant.telegram_bot_token = token
        db.commit()
        print(f"Обновлён тенант '{SLUG}', id={tenant.id}")
    else:
        tenant = Tenant(
            slug=SLUG,
            name="Lanternaweb",
            system_prompt=SYSTEM_PROMPT,
            telegram_bot_token=token or None,
            # Заявки шлём Денису в тот же чат, что и у demo-тенанта (личный chat_id из env)
            telegram_notify_chat_id=settings.telegram_notify_chat_id or None,
        )
        db.add(tenant)
        db.commit()
        print(f"Создан тенант '{SLUG}', id={tenant.id}")

    # Регистрируем вебхук Telegram на бота тенанта
    if token and settings.public_base_url:
        webhook_url = f"{settings.public_base_url}/webhook/telegram/{SLUG}"
        resp = httpx.post(
            f"https://api.telegram.org/bot{token}/setWebhook",
            json={"url": webhook_url},
            timeout=10,
        )
        print("setWebhook:", resp.json())
    else:
        print("Вебхук не поставлен: нужен LANTERNAWEB_TELEGRAM_TOKEN и PUBLIC_BASE_URL в env")


if __name__ == "__main__":
    run()
